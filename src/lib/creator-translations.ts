export function creatorText(locale: Locale, source: string | undefined, values: Record<string, string | number> = {}): string {
  if (!source) return "";
  const interpolate = (text: string, parameters = values) => text.replace(/\{(\w+)\}/g, (match, key: string) => String(parameters[key] ?? match));
  if (locale === "en") return interpolate(source);
  const direct = creatorTranslations[source]?.[locale];
  if (direct) return interpolate(direct);

  // These names are display labels assembled by the game-owned catalogue.
  // Matching whole labels keeps user-authored build names and exported IDs intact.
  const labelPatterns: [RegExp, string, string][] = [
    [/^(.+) basic attack presentation$/, "{className} basic attack presentation", "className"],
    [/^(.+) basic attack$/, "{className} basic attack", "className"],
    [/^(.+) presentation$/, "{name} presentation", "name"],
    ...["dagger", "scepter", "bow", "repeater", "sword", "launcher"].map((suffix): [RegExp, string, string] => [new RegExp(`^(.+) ${suffix}$`), `{className} ${suffix}`, "className"]),
  ];
  for (const [pattern, template, key] of labelPatterns) {
    const match = source.match(pattern);
    if (match && creatorTranslations[match[1]]) return creatorText(locale, template, {[key]: creatorText(locale, match[1])});
  }

  // Validators deliberately return canonical English errors. Translate at the
  // presentation boundary so changing language also updates existing feedback.
  const messagePatterns: [RegExp, string, string[]][] = [
    [/^(.+) requires a (\w+) core attack profile\.$/, "{skill} requires a {profile} core attack profile.", ["skill", "profile"]],
    [/^(.+) needs (.+) in the kit\.$/, "{skill} needs {skills} in the kit.", ["skill", "skills"]],
    [/^Skill (.+) is not composable in this catalogue\.$/, "Skill {id} is not composable in this catalogue.", ["id"]],
    [/^(.+) must contain (\d+)–(\d+) characters without control characters\.$/, "{field} must contain {min}–{max} characters without control characters.", ["field", "min", "max"]],
    [/^(.+) contains an unpaired Unicode surrogate\.$/, "{field} contains an unpaired Unicode surrogate.", ["field"]],
    [/^(.+) has missing or unsupported fields\.$/, "{field} has missing or unsupported fields.", ["field"]],
    [/^(.+) must be an object\.$/, "{field} must be an object.", ["field"]],
    [/^Duplicate JSON field: (.+)$/, "Duplicate JSON field: {field}", ["field"]],
    [/^Loaded account build version (.+)\. Your browser recovery draft will follow this editor\.$/, "Loaded account build version {version}. Your browser recovery draft will follow this editor.", ["version"]],
  ];
  for (const [pattern, template, keys] of messagePatterns) {
    const match = source.match(pattern);
    if (match) return creatorText(locale, template, Object.fromEntries(keys.map((key, index) => [key, key === "id" || key === "version" ? match[index + 1] : match[index + 1].split(" or ").map((value) => creatorText(locale, value)).join(locale === "ru" ? " или " : " 或 ")])));
  }
  const sentences = source.match(/[^.]+\.(?: |$)/g);
  if (sentences && sentences.join("") === source && sentences.length > 1) return sentences.map((sentence) => creatorText(locale, sentence.trim())).join(" ");
  return source;
}
